#Operadores aritméticos, relacionais e lógicos
print (1+1) #adição
print (1-1) #subtração
print (1*1) #multiplicação
print (1/1) #divisão
print (1%1) #módulo
print (1**1) #exponenciação
print (1//1) #divisão inteira
print (1==1) #igualdade
print (1!=1) #diferença
print (1>1) #maior que
print (1<1) #menor que
print (1>=1) #maior ou igual
print (1<=1) #menor ou igual
print (1 and 1) #e lógico
print (1 or 1) #ou lógico
print (not 1) #negação lógica